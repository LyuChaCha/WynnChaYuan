"""Subset Noto Sans TC (variable, SIL OFL 1.1) to the characters the zh site text uses and write site-fonts.js.

python tools/presence/build-site-fonts.py [--font <NotoSansTC-VF.ttf>] [--check]
"""
import base64
import hashlib
import io
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.join(HERE, 'site-fonts.js')
DEFAULT_FONT = r'C:\Windows\Fonts\NotoSansTC-VF.ttf'
SOURCES = ['site-pages.js', 'site-layout.js', 'site-constants.js']
EXTRA = '，。、；：？！「」『』（）《》〈〉…—・×→←↑↓～％＋－／＝　０１２３４５６７８９'


def site_text():
    code = ("import('./site-strings.js').then((m) => process.stdout.write(JSON.stringify(m.TEXT.zh)))")
    out = subprocess.run(['node', '--no-warnings', '-e', code], cwd=HERE, capture_output=True, check=True)
    return json.loads(out.stdout.decode('utf-8'))


def wanted():
    chars = set(chr(c) for c in range(0x20, 0x7f)) | set(EXTRA)
    def take(text):
        chars.update(re.sub(r'<[^>]+>', '', text))
    def walk(value):
        if isinstance(value, str):
            take(value)
        elif isinstance(value, dict):
            for item in value.values():
                walk(item)
        elif isinstance(value, list):
            for item in value:
                walk(item)
    walk(site_text())
    for name in SOURCES:
        with io.open(os.path.join(HERE, name), encoding='utf-8') as handle:
            take(''.join(c for c in handle.read() if ord(c) >= 0x2E80))
    return ''.join(sorted(c for c in chars if c >= ' ' and c not in '\u2028\u2029'))


def subset(path, chars):
    from fontTools import subset as tool
    from fontTools.ttLib import TTFont
    font = TTFont(path)
    have = font.getBestCmap()
    covered = ''.join(c for c in chars if ord(c) in have)
    options = tool.Options()
    options.layout_features = ['kern', 'locl', 'ccmp', 'mark', 'mkmk']
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.notdef_outline = True
    options.hinting = False
    options.flavor = 'woff'
    worker = tool.Subsetter(options)
    worker.populate(unicodes=[ord(c) for c in covered])
    worker.subset(font)
    font.flavor = 'woff'
    out = io.BytesIO()
    font.save(out)
    return out.getvalue(), covered


def render(data, covered, absent):
    fonts = {'tc': {'covers': covered, 'absent': absent, 'v': hashlib.sha256(data).hexdigest()[:10],
                    'data': base64.b64encode(data).decode('ascii')}}
    return ('/**\n * Site text face: Noto Sans TC, variable weight (SIL Open Font License 1.1), subset to the zh site text.\n'
            ' * Generated by build-site-fonts.py; do not edit by hand.\n */\n'
            'export const UI_FONTS = ' + json.dumps(fonts, ensure_ascii=False, indent=1) + ';\n')


def main():
    need = wanted()
    if '--check' in sys.argv:
        with io.open(TARGET, encoding='utf-8') as handle:
                text = handle.read()
        known = ''
        for field in ('covers', 'absent'):
            match = re.search(r'"' + field + r'": ("(?:[^"\\]|\\.)*")', text)
            known += json.loads(match.group(1)) if match else ''
        missing = ''.join(c for c in need if c not in known and ord(c) >= 0x2E80)
        if missing:
            sys.exit('site-fonts.js is missing: ' + missing + ' (rerun build-site-fonts.py)')
        return
    path = sys.argv[sys.argv.index('--font') + 1] if '--font' in sys.argv else DEFAULT_FONT
    data, covered = subset(path, need)
    with io.open(TARGET, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write(render(data, covered, ''.join(c for c in need if c not in covered)))
    print('site-fonts.js: %d characters, %d bytes woff' % (len(covered), len(data)))


if __name__ == '__main__':
    main()
