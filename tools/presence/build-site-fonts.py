"""Subset Fusion Pixel 10px (SIL OFL 1.1, shipped with the mod) to the site's text, one WOFF per script, into site-fonts.js.

python tools/presence/build-site-fonts.py [--check]
"""
import base64
import hashlib
import io
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
FONTS = os.path.join(ROOT, 'src', 'main', 'resources', 'assets', 'wynnchayuan', 'font')
CREDITS = os.path.join(ROOT, 'src', 'main', 'resources', 'assets', 'wynnchayuan', 'credits.json')
TARGET = os.path.join(HERE, 'site-fonts.js')
SOURCES = ['site-pages.js', 'site-layout.js', 'site-constants.js']
EXTRA = '，。、；：？！「」『』（）《》〈〉…—・×→←↑↓～％＋－／＝·“”‘’★'
SETS = [
    ('latin', 'fusion_pixel_10px_zh_hant.ttf', None),
    ('tc', 'fusion_pixel_10px_zh_hant.ttf', 'zh'),
    ('sc', 'fusion-pixel-10pxl-zh_hans.ttf', 'zh-cn'),
    ('ja', 'fusion-pixel-10px-ja.ttf', 'ja'),
    ('ko', 'fusion-pixel-10px-ko.ttf', 'ko'),
]


def site_text():
    code = ("import('./site-strings.js').then((m) => process.stdout.write(JSON.stringify("
            "{ text: m.TEXT, names: m.LANG_NAMES })))")
    out = subprocess.run(['node', '--no-warnings', '-e', code], cwd=HERE, capture_output=True, check=True)
    return json.loads(out.stdout.decode('utf-8'))


def letters(value):
    found = set()
    def walk(item):
        if isinstance(item, str):
            found.update(re.sub(r'<[^>]+>', '', item))
        elif isinstance(item, dict):
            for inner in item.values():
                walk(inner)
        elif isinstance(item, list):
            for inner in item:
                walk(inner)
    walk(value)
    return found


def cjk(chars):
    return {c for c in chars if ord(c) >= 0x2E80}


def wanted():
    data = site_text()
    shared = set(chr(c) for c in range(0x20, 0x7f)) | set(EXTRA) | letters(data['names'])
    for text in data['text'].values():
        shared |= {c for c in letters(text) if 0x20 <= ord(c) < 0x2E80}
    with io.open(CREDITS, encoding='utf-8') as handle:
        people = letters(json.load(handle))
    markup = set()
    for name in SOURCES:
        with io.open(os.path.join(HERE, name), encoding='utf-8') as handle:
            markup |= cjk(handle.read())
    need = {}
    for code, _, lang in SETS:
        chars = set(shared) | {c for c in people if 0x20 <= ord(c) < 0x2E80}
        if lang:
            chars |= cjk(letters(data['text'][lang])) | markup | cjk(people)
        need[code] = ''.join(sorted(c for c in chars if c not in '  '))
    return need


def subset(name, chars):
    from fontTools import subset as tool
    from fontTools.ttLib import TTFont
    font = TTFont(os.path.join(FONTS, name))
    have = font.getBestCmap()
    covered = ''.join(c for c in chars if ord(c) in have)
    options = tool.Options()
    options.layout_features = []
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.notdef_outline = True
    options.hinting = False
    worker = tool.Subsetter(options)
    worker.populate(unicodes=[ord(c) for c in covered])
    worker.subset(font)
    font.flavor = 'woff'
    out = io.BytesIO()
    font.save(out)
    return out.getvalue(), covered


def main():
    need = wanted()
    if '--check' in sys.argv:
        with io.open(TARGET, encoding='utf-8') as handle:
            text = handle.read()
        fonts = json.loads(text[text.index('{'):text.rindex('}') + 1])
        missing = {code: ''.join(c for c in need[code] if c not in fonts[code]['covers'] + fonts[code]['absent'])
                   for code, _, _ in SETS}
        missing = {code: chars for code, chars in missing.items() if chars}
        if missing:
            sys.exit('site-fonts.js is missing: ' + json.dumps(missing, ensure_ascii=False) + ' (rerun build-site-fonts.py)')
        return
    fonts = {}
    for code, name, _ in SETS:
        data, covered = subset(name, need[code])
        fonts[code] = {'covers': covered, 'absent': ''.join(c for c in need[code] if c not in covered),
                       'v': hashlib.sha256(data).hexdigest()[:10], 'data': base64.b64encode(data).decode('ascii')}
        print('%s: %d characters, %d bytes woff' % (code, len(covered), len(data)))
    body = json.dumps(fonts, ensure_ascii=False, indent=1)
    with io.open(TARGET, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write('/**\n * Site text face: Fusion Pixel 10px (SIL Open Font License 1.1, '
                     'assets/wynnchayuan/font/ofl-fusion.txt), one subset per script.\n'
                     ' * Generated by build-site-fonts.py; do not edit by hand.\n */\n'
                     'export const UI_FONTS = ' + body + ';\n')


if __name__ == '__main__':
    main()
